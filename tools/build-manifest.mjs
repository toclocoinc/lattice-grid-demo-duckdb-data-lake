/**
 * Lists the latest Overture Maps release's Places files and writes src/manifest.js.
 *
 * Nothing is downloaded but listings and Parquet footers: the bucket is listed
 * over HTTPS (it allows anonymous listing), and each file's footer is read once
 * with @duckdb/node-api to record its size, row count, row-group count and the
 * longitude/latitude extent of its row groups. The page reads this file instead
 * of opening 17 footers (about 1.6 MB each) just to learn which files to skip.
 *
 *   node tools/build-manifest.mjs            # latest release
 *   node tools/build-manifest.mjs 2026-09-23.1
 */

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { DuckDBInstance } from '@duckdb/node-api';

const HOST = 'https://overturemaps-us-west-2.s3.amazonaws.com';

async function list(prefix, delimiter) {
  const out = { keys: [], prefixes: [] };
  let token = '';
  do {
    const url = `${HOST}/?list-type=2&prefix=${encodeURIComponent(prefix)}${delimiter ? '&delimiter=/' : ''}${token ? `&continuation-token=${encodeURIComponent(token)}` : ''}`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: ${response.status}`);
    const xml = await response.text();
    for (const m of xml.matchAll(/<Contents><Key>([^<]+)<\/Key>.*?<Size>(\d+)<\/Size>/gs)) out.keys.push({ key: m[1], size: Number(m[2]) });
    for (const m of xml.matchAll(/<Prefix>([^<]+)<\/Prefix>/g)) if (m[1] !== prefix) out.prefixes.push(m[1]);
    token = /<IsTruncated>true/.test(xml) ? /<NextContinuationToken>([^<]+)</.exec(xml)?.[1] ?? '' : '';
  } while (token);
  return out;
}

const wanted = process.argv[2];
const releases = (await list('release/', true)).prefixes.map((p) => p.split('/')[1]).sort();
const release = wanted ?? releases.at(-1);
const files = (await list(`release/${release}/theme=places/type=place/`)).keys
  .filter((f) => f.key.endsWith('.parquet'))
  .sort((a, b) => a.key.localeCompare(b.key));
if (!files.length) throw new Error(`No Places files in release ${release}`);

const db = await DuckDBInstance.create(':memory:');
const conn = await db.connect();
await conn.run('INSTALL httpfs; LOAD httpfs;');

const entries = [];
for (const f of files) {
  const url = `${HOST}/${f.key}`;
  const meta = (await conn.runAndReadAll(`SELECT num_rows, num_row_groups FROM parquet_file_metadata('${url}')`)).getRowObjectsJson()[0];
  const ext = (await conn.runAndReadAll(`
    SELECT
      min(stats_min::double) FILTER (path_in_schema = 'bbox, xmin') AS xmin,
      max(stats_max::double) FILTER (path_in_schema = 'bbox, xmax') AS xmax,
      min(stats_min::double) FILTER (path_in_schema = 'bbox, ymin') AS ymin,
      max(stats_max::double) FILTER (path_in_schema = 'bbox, ymax') AS ymax
    FROM parquet_metadata('${url}')`)).getRowObjectsJson()[0];
  entries.push({
    name: f.key.split('/').pop(), size: f.size,
    rows: Number(meta.num_rows), rowGroups: Number(meta.num_row_groups),
    xmin: ext.xmin, ymin: ext.ymin, xmax: ext.xmax, ymax: ext.ymax,
  });
  console.log(entries.at(-1).name, entries.at(-1).rows, entries.at(-1).size);
}

const totalBytes = entries.reduce((s, e) => s + e.size, 0);
const totalRows = entries.reduce((s, e) => s + e.rows, 0);
const body = `/**
 * The Overture Maps Places files, generated by tools/build-manifest.mjs.
 * Do not edit by hand. Generated for release ${release}.
 *
 * DuckDB cannot glob an https path, so the page needs the list of files. The
 * extents are the longitude/latitude range of each file's row groups, read
 * from its footer once, so the page opens only the files a map window can touch.
 */
export const MANIFEST = ${JSON.stringify({
    release,
    host: HOST,
    prefix: `release/${release}/theme=places/type=place/`,
    totalBytes, totalRows, files: entries,
  }, null, 1)};
`;
await writeFile(fileURLToPath(new URL('../src/manifest.js', import.meta.url)), body);
console.log(`release ${release}: ${entries.length} files, ${totalRows} rows, ${(totalBytes / 1e9).toFixed(2)} GB`);
